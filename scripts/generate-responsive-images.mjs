import { mkdir, writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const origin = 'https://Tripways-static-assets.leultesfaye0755.workers.dev'
const output = new URL('../src/assets/photos/', import.meta.url)
const photos = {
  infinityPool: 'infinity-pool',
  hotelLobby: 'hotel-lobby',
  trifwaysLakesideHotel: 'trifways-lakeside-hotel',
  mountainLodge: 'mountain-lodge',
  rusticSuite: 'rustic-suite',
  adventureLodge: 'adventure-lodge',
}
const imports = []
const entries = []
await mkdir(output, { recursive: true })

// Generate real image variants locally so production builds need no resizing service
for (const [key, name] of Object.entries(photos)) {
  const response = await fetch(`${origin}/${name}.webp`)
  if (!response.ok)
    throw new Error(`Cannot download ${name}: ${response.status}`)
  const original = Buffer.from(await response.arrayBuffer())
  const { width } = await sharp(original).metadata()
  if (!width) throw new Error(`Missing image width: ${name}`)
  // Retain the original maximum resolution without generating enlarged copies
  const widths = [
    ...new Set([320, 640, 960, 1440, width].filter((size) => size <= width)),
  ].sort((a, b) => a - b)
  const candidates = []
  for (const size of widths) {
    const file = `${name}-${size}.webp`
    // Preserve the largest original; encode only the smaller display variants
    const image =
      size === width
        ? original
        : await sharp(original)
            .resize({ width: size })
            .webp({ quality: 82 })
            .toBuffer()
    await writeFile(new URL(file, output), image)
    const variable = `${key}${size}`
    imports.push(`import ${variable} from '../assets/photos/${file}'`)
    candidates.push(`\${${variable}} ${size}w`)
    console.log(`${file}: ${image.length} bytes (original ${original.length})`)
  }
  entries.push(
    `  ${key}: { src: ${key}${width}, srcSet: \`${candidates.join(', ')}\` },`,
  )
}

// Vite fingerprints imported photos and keeps only their URLs in the JavaScript bundle
await writeFile(
  new URL('../src/lib/staticPhotos.ts', import.meta.url),
  `// Generated by npm run images:generate\n${imports.join('\n')}\n\nexport const staticPhotos = {\n${entries.join('\n')}\n} as const\n`,
)
